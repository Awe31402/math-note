# E4-06: class AB push-pull output stage biased by two diodes
import sys, os; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import save, drawing
import schemdraw.elements as elm
with drawing() as d:
    src = elm.SourceI().down().at((0, 3)).label('$I_{bias}$', loc='top')
    b1 = elm.Dot().at(src.end)
    elm.Diode().down().at(b1.center).label('$D_1$', loc='top'); elm.Diode().down().label('$D_2$', loc='top')
    b2 = elm.Dot()
    elm.Line().down().length(0.4)
    q3 = elm.BjtNpn().right().anchor('collector')
    elm.Line().left().at(q3.base).length(0.6); elm.Dot(open=True).label('$v_i$', loc='left')
    elm.Line().down().at(q3.emitter).length(0.3); elm.Vss().label('$-V_{CC}$')
    elm.Line().right().at(b1.center).length(1.5)
    qn = elm.BjtNpn().right().anchor('base')
    elm.Line().up().at(qn.collector).length(0.4); elm.Vdd().label('$V_{CC}$')
    elm.Line().right().at(b2.center).length(1.5)
    qp = elm.BjtPnp().right().anchor('base')
    elm.Line().down().at(qp.collector).length(0.4); elm.Vss().label('$-V_{CC}$')
    elm.Line().at(qn.emitter).to(qp.emitter)
    o = ((qn.emitter[0] + qp.emitter[0]) / 2, (qn.emitter[1] + qp.emitter[1]) / 2); elm.Dot().at(o)
    elm.Line().right().at(o).length(1.6); p = elm.Dot()
    elm.Resistor().down().at(p.center).label('$R_L$', loc='bottom'); elm.Ground()
    elm.Line().right().at(p.center).length(0.6); elm.Dot(open=True).label('$v_o$', loc='right')
    elm.Label().at((qn.base[0] + 1.4, qn.base[1] + 0.3)).label('$Q_N$')
    elm.Label().at((qp.base[0] + 1.4, qp.base[1] - 0.3)).label('$Q_P$')
    elm.Label().at((q3.base[0] + 1.4, q3.base[1])).label('driver')
    elm.Vdd().at((0, 3)).label('$V_{CC}$')
    save(d, 'E4-06-class-ab')
